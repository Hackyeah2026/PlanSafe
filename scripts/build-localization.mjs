import { readFile, writeFile, mkdir } from "node:fs/promises";
import { format } from "prettier";

// Export string-only .resx resources for UI owned by JavaScript and pre-Blazor errors.
// The .resx files remain the only maintained translation catalogue.
const root = new URL("../src/PlanSafe.App/", import.meta.url);
function decode(value) {
  return value.replace(
    /&(amp|lt|gt|quot|apos|#\d+|#x[\da-f]+);/gi,
    (_, entity) => {
      const named = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'" };
      return (
        named[entity] ??
        String.fromCodePoint(
          entity.startsWith("#x")
            ? parseInt(entity.slice(2), 16)
            : Number(entity.slice(1)),
        )
      );
    },
  );
}
const catalogues = {};
for (const [language, suffix] of [
  ["en", ""],
  ["pl", ".pl"],
]) {
  const xml = await readFile(
    new URL(`Resources/UiStrings${suffix}.resx`, root),
    "utf8",
  );
  const entries = [
    ...xml.matchAll(
      /<data\s+name="([^"]+)"[^>]*>\s*<value>([\s\S]*?)<\/value>\s*<\/data>/g,
    ),
  ];
  if (
    entries.length !== (xml.match(/<data\s/g) ?? []).length ||
    !entries.length
  ) {
    throw new Error(
      "Localization resources must contain string-only data/value entries.",
    );
  }
  catalogues[language] = Object.fromEntries(
    entries.map(([, key, value]) => [decode(key), decode(value)]),
  );
  if (
    new Set(Object.keys(catalogues[language]).map((key) => key.toLowerCase()))
      .size !== entries.length
  )
    throw new Error("Duplicate localization key.");
}
const keys = Object.keys(catalogues.en).sort();
if (
  JSON.stringify(keys) !== JSON.stringify(Object.keys(catalogues.pl).sort())
) {
  throw new Error("English and Polish translation keys must match.");
}
for (const key of keys) {
  const placeholders = (value) =>
    [...value.matchAll(/\{\d+(?:[^}]*)\}/g)].map((match) => match[0]).sort();
  if (
    JSON.stringify(placeholders(catalogues.en[key])) !==
    JSON.stringify(placeholders(catalogues.pl[key]))
  ) {
    throw new Error(`Translation placeholders differ: ${key}`);
  }
}
await mkdir(new URL("wwwroot/js/", root), { recursive: true });
// Generate the same nested references for Razor/C# and TypeScript/JavaScript.
const domains = {};
for (const key of keys) {
  if (!/^[A-Z][A-Za-z0-9]*\.[A-Z][A-Za-z0-9]*$/.test(key))
    throw new Error(`Expected a Domain.Name localization key: ${key}`);
  const [domain, name] = key.split(".");
  (domains[domain] ??= {})[name] = key;
}
async function writeChanged(path, value) {
  if (path.endsWith(".ts"))
    value = await format(value, { parser: "typescript" });
  const url = new URL(path, root);
  if ((await readFile(url, "utf8").catch(() => null)) !== value)
    await writeFile(url, value);
}
await writeChanged(
  "Localization/LocalizedText.g.cs",
  "// <auto-generated />\nusing Microsoft.Extensions.Localization;\n\nnamespace PlanSafe.App.Localization;\n\npublic sealed class LocalizedText(IStringLocalizer<UiStrings> strings)\n{\n" +
    Object.keys(domains)
      .map(
        (domain) =>
          `    public ${domain}Text ${domain} { get; } = new(strings);\n`,
      )
      .join("") +
    "\n" +
    Object.entries(domains)
      .map(
        ([domain, entries]) =>
          `    public sealed class ${domain}Text(IStringLocalizer<UiStrings> strings)\n    {\n` +
          Object.entries(entries)
            .map(([name, key]) => {
              const indices = [
                ...catalogues.en[key].matchAll(/\{(\d+)(?:[^}]*)\}/g),
              ].map((m) => Number(m[1]));
              const count = indices.length ? Math.max(...indices) + 1 : 0;
              const args = Array.from({ length: count }, (_, i) => `arg${i}`);
              return count
                ? `        public string ${name}(${args.map((a) => "object " + a).join(", ")}) => strings["${key}", ${args.join(", ")}].Value;\n`
                : `        public string ${name} => strings["${key}"].Value;\n`;
            })
            .join("") +
          "    }\n",
      )
      .join("\n") +
    "}\n",
);
await writeChanged(
  "TypeScript/textKeys.ts",
  "// Generated from Resources/UiStrings.resx. Do not edit.\n" +
    `export const TextKeys = ${JSON.stringify(domains, null, 2)} as const;\n` +
    "type Domains = typeof TextKeys;\n" +
    "export type TextKey = { [D in keyof Domains]: Domains[D][keyof Domains[D]] }[keyof Domains];\n" +
    `export const englishText: Record<TextKey, string> = ${JSON.stringify(catalogues.en, null, 2)};\n`,
);
await writeChanged(
  "wwwroot/js/translations.js",
  `// Generated from Resources/UiStrings*.resx.\nwindow.planSafeTranslations = ${JSON.stringify(catalogues)};\nwindow.planSafeTextKeys = ${JSON.stringify(domains)};\n`,
);
